package com.malto4.pipdroid

/**
 * Три режима работы приложения (roadmap, "Видение приложения — финальная точка", п.1).
 *
 * PHONE — fullscreen, управление тачскрином, без внешнего железа. Для игроков без корпуса.
 * PIPBOY_2000 — телефон внутри корпуса, тачскрин закрыт, управление только через BLE-
 * периферию (кнопки/энкодеры/тумблеры, см. PipBoy_BLE_Protocol_v0.2.md).
 * PIPBOY_3000 — заглушка на будущее: тот же принцип, что у 2000, другая конфигурация
 * внешнего железа. Пока не реализована — ведёт себя как PIPBOY_2000.
 */
enum class PipBoyMode {
    PHONE,
    PIPBOY_2000,
    PIPBOY_3000,
}
